assign = json.load(open(ROOT + r"\decisions\assign3.json", encoding="utf-8"))
missing = [i for i in assign if i not in D]
extra = [i for i in D if i not in assign]
assert not missing and not extra, (missing, extra)
VALID = {REQ, ADOPT, COND, ALT, NO, BAN, NA}
out = [D[i] for i in assign]
own = {}
for r in out:
    for c in "ABC":
        x = r[c]
        assert x["judgement"] in VALID
        if x["judgement"] == COND: assert x["condition"], (r["id"], c)
        else: assert x["condition"] == "", (r["id"], c)
        if x["judgement"] == ALT: assert x["alt"], (r["id"], c)
        else: assert not x["alt"], (r["id"], c)
        assert x["use_or_loss"], (r["id"], c)
        if x["judgement"] == COND or x["judgement"].startswith("不採用"): assert x["revisit"], (r["id"], c)
        own[(r["id"], c)] = x["judgement"]
outside = set()
for r in out:
    for c in "ABC":
        for a in r[c]["alt"]:
            if (a, c) in own:
                assert own[(a, c)] in (REQ, ADOPT, COND), (r["id"], c, a, own[(a, c)])
            else:
                outside.add((a, c))
json.dump(out, open(ROOT + r"\decisions\part3.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
